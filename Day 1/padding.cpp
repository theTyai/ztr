#include<bits/stdc++.h>
using namespace std;

int main()
{
    int a=2;//00010
    int b=4;//00100
    cout<<"Left Padding: multiply 2 to the no given"<<endl;
    cout<<"a<<1: "<<(a<<1)<<endl;
    cout<<"a<<2: "<<(a<<2)<<endl;
    cout<<"Right Padding: divide 2 to the no given"<<endl;
    cout<<"b>>1: "<<(b>>1)<<endl;
    cout<<"b>>2: "<<(b>>2)<<endl;
    return 0;
}